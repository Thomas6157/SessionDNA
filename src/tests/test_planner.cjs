const assert=require('node:assert/strict');
const P=require('../triathlon_web/planner.js');
const p={wake:'07:00',bed:'22:00',commute:30,before:15,after:15,swimExtra:20};
const s={id:'run',date:'2026-09-28',sport:'running',planned_duration_min:60};
const events=[{start:'2026-09-28T08:15:00+02:00',end:'2026-09-28T09:45:00+02:00',title:'Cours'}];
assert(P.validate(p));assert(!P.validate({...p,commute:''}));assert(!P.validate({...p,bed:'03:00'}));
assert(P.conflicts(s,'07:15',p,events,[s],{}).some(x=>x.startsWith('Cours')));
assert.equal(P.conflicts(s,'10:30',p,events,[s],{}).length,0);
assert(P.conflicts(s,'21:00',p,events,[s],{}).includes('Sommeil / limites de journée'));
assert(P.conflicts(s,'11:00',p,[],[s,{...s,id:'bike',title:'Vélo'}],{bike:'10:30'}).length);
assert.equal(P.courses([{start:'2026-09-27T00:00:00+02:00',end:'2026-09-28T00:00:00+02:00'}],s.date).length,0);
assert.equal(P.interval({...s,sport:'swimming'},'12:00',p).end,815);
assert(!P.overlap({start:1,end:2},{start:2,end:3}));
console.log('Planning : horaires, marges, conflits, sommeil et jours entiers vérifiés.');
const pool=require('../planning_preferences.json').pool;
const swim={...s,sport:'swimming'};
assert(P.conflicts(swim,'10:00',p,[],[swim],{},pool).some(x=>x.startsWith('Piscine')));
assert.equal(P.conflicts(swim,'12:15',p,[],[swim],{},pool).length,0);
assert(P.conflicts(swim,'20:30',p,[],[swim],{},pool).some(x=>x.startsWith('Piscine')));
assert(P.conflicts({...swim,date:'2026-12-25'},'12:15',p,[],[],{},pool).some(x=>x.startsWith('Horaires piscine')));
console.log('Piscine : ouverture du lundi, fin avant évacuation et validité des horaires vérifiées.');
